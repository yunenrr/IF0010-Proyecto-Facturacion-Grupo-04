IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_RESUMEN_FACTURAS'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_RESUMEN_FACTURAS;
    END
GO

CREATE VIEW DBO.VW_RESUMEN_FACTURAS
AS
SELECT
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    E.RAZON_SOCIAL AS EMPRESA,
    TD.DESCRIPCION AS TIPO_DOCUMENTO,
    M.CODIGO AS MONEDA,
    EF.DESCRIPCION AS ESTADO,
    F.TOTAL,
    CASE
        WHEN CJ.CEDULA_CLIENTE IS NOT NULL
            THEN CJ.RAZON_SOCIAL
        ELSE CONCAT(
            CF.NOMBRE,
            ' ',
            CF.PRIMER_APELLIDO,
            ' ',
            CF.SEGUNDO_APELLIDO
        )
    END AS CLIENTE
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA AS E
    ON F.CEDULA_EMPRESA = E.CEDULA
INNER JOIN DBO.CLIENTE AS C
    ON F.CEDULA_CLIENTE = C.CEDULA
LEFT JOIN DBO.CLIENTEFISICO AS CF
    ON C.CEDULA = CF.CEDULA_CLIENTE
LEFT JOIN DBO.CLIENTEJURIDICO AS CJ
    ON C.CEDULA = CJ.CEDULA_CLIENTE
INNER JOIN DBO.TIPODOCUMENTO AS TD
    ON F.CODIGO_TIPO_DOCUMENTO = TD.CODIGO
INNER JOIN DBO.MONEDA AS M
    ON F.CODIGO_MONEDA = M.CODIGO
INNER JOIN DBO.ESTADOFACTURA AS EF
    ON F.ESTADO_FACTURA = EF.ESTADO;
GO
