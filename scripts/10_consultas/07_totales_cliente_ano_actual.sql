USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

SELECT
    F.CEDULA_CLIENTE,
    COALESCE(SUM(F.TOTAL_DESCUENTOS), 0) AS TOTAL_DESCUENTOS,
    COALESCE(SUM(F.TOTAL_IMPUESTOS), 0) AS TOTAL_IMPUESTOS,
    COALESCE(SUM(F.TOTAL), 0) AS MONTO_TOTAL_FACTURADO
FROM DBO.FACTURA AS F
WHERE
    F.CEDULA_CLIENTE = '1-1000-0001'
    AND F.FECHA_EMISION >= DATEFROMPARTS(
        YEAR(SYSDATETIME()),
        1,
        1
    )
    AND F.FECHA_EMISION < DATEADD(
        YEAR,
        1,
        DATEFROMPARTS(YEAR(SYSDATETIME()), 1, 1)
    )
    AND F.FECHA_EMISION <= SYSDATETIME()
GROUP BY F.CEDULA_CLIENTE;
GO
