SELECT
    F.ID_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.CEDULA_EMPRESA,
    F.CEDULA_CLIENTE,
    F.CODIGO_TIPO_DOCUMENTO,
    F.CODIGO_MONEDA,
    F.ESTADO_FACTURA,
    F.FECHA_EMISION,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.TOTAL_IMPUESTOS,
    F.TOTAL,
    F.OBSERVACIONES,
    F.FECHA_CREACION,
    F.FECHA_MODIFICACION
FROM DBO.FACTURA AS F
INNER JOIN DBO.CLIENTEJURIDICO AS CJ
    ON F.CEDULA_CLIENTE = CJ.CEDULA_CLIENTE
WHERE CJ.CEDULA_CLIENTE = '3-101-000001';
GO
