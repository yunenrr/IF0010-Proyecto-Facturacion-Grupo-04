SELECT
    F.IDENTIFICADOR_COMPROBANTE,
    D.CANTIDAD,
    F.FECHA_EMISION
FROM DBO.DETALLEPRODUCTO AS DP
INNER JOIN DBO.DETALLEFACTURA AS D
    ON DP.ID_FACTURA = D.ID_FACTURA
    AND DP.NUMERO_LINEA = D.NUMERO_LINEA
INNER JOIN DBO.FACTURA AS F
    ON D.ID_FACTURA = F.ID_FACTURA
WHERE
    DP.CODIGO_PRODUCTO = 'PROD-GENERADO-1'
    AND F.FECHA_EMISION >= '2026-01-01'
    AND F.FECHA_EMISION < '2026-12-01';
GO
