GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'VW_TOTALES_DIARIOS_EMPRESA'
            AND TYPE = 'V'
    )
    BEGIN
        DROP VIEW DBO.VW_TOTALES_DIARIOS_EMPRESA;
    END
GO

CREATE VIEW DBO.VW_TOTALES_DIARIOS_EMPRESA
AS
SELECT
    E.RAZON_SOCIAL AS NOMBRE_EMPRESA,
    TD.DESCRIPCION AS TIPO_DOCUMENTO,
    CONVERT(
        DATE,
        F.FECHA_EMISION
    ) AS FECHA_EMISION,
    COUNT(*) AS CANTIDAD_FACTURAS,
    SUM(F.SUBTOTAL) AS SUBTOTAL_ACUMULADO,
    SUM(F.TOTAL_DESCUENTOS) AS TOTAL_DESCUENTOS,
    SUM(F.TOTAL_IMPUESTOS) AS TOTAL_IMPUESTOS,
    SUM(F.TOTAL) AS MONTO_TOTAL_FACTURADO
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA AS E
    ON F.CEDULA_EMPRESA = E.CEDULA
INNER JOIN DBO.TIPODOCUMENTO AS TD
    ON F.CODIGO_TIPO_DOCUMENTO = TD.CODIGO
GROUP BY
    E.RAZON_SOCIAL,
    TD.DESCRIPCION,
    CONVERT(
        DATE,
        F.FECHA_EMISION
    );
GO
