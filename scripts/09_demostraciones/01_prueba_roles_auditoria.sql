DECLARE @COMANDO NVARCHAR(MAX);

SET @COMANDO = N'
EXECUTE AS USER = ''USUARIO_AUDITOR'';

SELECT
    USER_NAME() AS USUARIO_ACTUAL,
    IS_MEMBER(''AUDITOR'') AS ES_AUDITOR,
    IS_MEMBER(''DBA'') AS ES_DBA;

SELECT TOP (10)
    A.ID_AUDITORIA,
    A.TABLA_AFECTADA,
    A.ID_REGISTRO,
    A.OPERACION,
    A.VALOR_ANTERIOR,
    A.VALOR_NUEVO,
    A.USUARIO,
    A.FECHA_HORA,
    A.DESCRIPCION
FROM DBO.FN_HISTORIAL_CAMBIOS() AS A
ORDER BY A.ID_AUDITORIA DESC;

REVERT;
';

EXEC SYS.SP_EXECUTESQL
    @COMANDO;

