USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_FACTURA_MODIFICABLE'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_FACTURA_MODIFICABLE;
    END
GO

CREATE FUNCTION DBO.FN_FACTURA_MODIFICABLE(
    @IDENTIFICADOR_COMPROBANTE VARCHAR(40)
)
RETURNS INT
AS
BEGIN
    DECLARE @ES_MODIFICABLE INT = 0;

    SELECT
        @ES_MODIFICABLE = CASE
            WHEN F.ESTADO_FACTURA = 'BORRADOR' THEN 1
            ELSE 0
        END
    FROM DBO.FACTURA AS F
    WHERE
        F.IDENTIFICADOR_COMPROBANTE
        = TRIM(@IDENTIFICADOR_COMPROBANTE);

    RETURN @ES_MODIFICABLE;
END;
GO
