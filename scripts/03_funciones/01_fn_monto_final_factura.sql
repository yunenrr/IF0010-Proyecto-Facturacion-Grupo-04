USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_MONTO_FINAL_FACTURA'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_MONTO_FINAL_FACTURA;
    END
GO

CREATE FUNCTION DBO.FN_MONTO_FINAL_FACTURA(
    @ID_FACTURA BIGINT
)
RETURNS DECIMAL(18, 2)
AS
BEGIN
    DECLARE @MONTO_FINAL DECIMAL(18, 2);

    SELECT
        @MONTO_FINAL = (
            F.SUBTOTAL
            - F.TOTAL_DESCUENTOS
            + F.TOTAL_IMPUESTOS
        )
    FROM DBO.FACTURA AS F
    WHERE F.ID_FACTURA = @ID_FACTURA;

    RETURN @MONTO_FINAL;
END;
GO
