USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_HISTORIAL_CAMBIOS'
            AND TYPE = 'IF'
    )
    BEGIN
        DROP FUNCTION DBO.FN_HISTORIAL_CAMBIOS;
    END
GO

CREATE FUNCTION DBO.FN_HISTORIAL_CAMBIOS ()
RETURNS TABLE
AS
RETURN (
    SELECT
        A.ID_AUDITORIA,
        A.TABLA_AFECTADA,
        A.ID_REGISTRO,
        A.OPERACION,
        A.VALOR_ANTERIOR,
        A.VALOR_NUEVO,
        A.USUARIO,
        A.FECHA_HORA,
        A.DESCRIPCION
    FROM DBO.AUDITORIA AS A
    WHERE
        IS_MEMBER('AUDITOR') = 1
        OR IS_MEMBER('DBA') = 1
);
GO

GRANT SELECT
ON DBO.FN_HISTORIAL_CAMBIOS
TO AUDITOR;
GO

GRANT SELECT
ON DBO.FN_HISTORIAL_CAMBIOS
TO DBA;
GO

GRANT SELECT
ON DBO.FN_HISTORIAL_CAMBIOS
TO USUARIO_SIN_ROL;
GO
