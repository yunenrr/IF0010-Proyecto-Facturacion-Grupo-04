USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_FACTURAS_CLIENTE'
            AND TYPE = 'IF'
    )
    BEGIN
        DROP FUNCTION DBO.FN_FACTURAS_CLIENTE;
    END
GO

CREATE FUNCTION DBO.FN_FACTURAS_CLIENTE (
    @CEDULA_CLIENTE VARCHAR(20)
)
RETURNS TABLE
AS
RETURN (
    SELECT
        F.IDENTIFICADOR_COMPROBANTE,
        F.FECHA_EMISION,
        TD.DESCRIPCION AS TIPO_DOCUMENTO,
        F.ESTADO_FACTURA,
        F.CODIGO_MONEDA AS MONEDA,
        F.TOTAL
    FROM DBO.FACTURA AS F
    INNER JOIN DBO.TIPODOCUMENTO AS TD
        ON F.CODIGO_TIPO_DOCUMENTO = TD.CODIGO
    WHERE F.CEDULA_CLIENTE = TRIM(@CEDULA_CLIENTE)
);
GO
