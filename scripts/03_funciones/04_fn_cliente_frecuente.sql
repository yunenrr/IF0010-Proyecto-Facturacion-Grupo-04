USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_CLIENTE_FRECUENTE'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_CLIENTE_FRECUENTE;
    END
GO

CREATE FUNCTION DBO.FN_CLIENTE_FRECUENTE(
    @CEDULA VARCHAR(20)
)
RETURNS NVARCHAR(2)
AS
BEGIN
    DECLARE @CANTIDAD_COMPRAS INT;

    SELECT @CANTIDAD_COMPRAS = COUNT(*)
    FROM DBO.FACTURA AS F
    WHERE
        F.CEDULA_CLIENTE = TRIM(@CEDULA)
        AND F.FECHA_EMISION >= DATEADD(
            MONTH,
            -6,
            SYSDATETIME()
        )
        AND F.FECHA_EMISION <= SYSDATETIME();

    RETURN CASE
        WHEN @CANTIDAD_COMPRAS > 5 THEN N'Sí'
        ELSE N'No'
    END;
END;
GO
