USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA_CLIENTE VARCHAR(20);

SELECT TOP (1)
    @CEDULA_CLIENTE = C.CEDULA
FROM DBO.CLIENTE AS C
ORDER BY C.CEDULA;

EXECUTE AS USER = 'USUARIO_ADMINISTRATIVO';

SELECT
    USER_NAME() AS USUARIO_ACTUAL,
    IS_MEMBER(
        'ROL_ADMINISTRATIVO'
    ) AS ES_ADMINISTRATIVO,
    IS_MEMBER(
        'ROL_OPERATIVO'
    ) AS ES_OPERATIVO;

SELECT
    C.CEDULA,
    C.TIPO_CLIENTE,
    C.NOMBRE,
    C.RAZON_SOCIAL,
    C.SENAS_EXACTAS,
    C.TELEFONO,
    C.CORREO,
    C.FECHA_REGISTRO,
    C.FECHA_ACTUALIZACION
FROM DBO.FN_INFORMACION_CLIENTE(
    @CEDULA_CLIENTE
) AS C;

REVERT;
GO

