USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

DECLARE @CEDULA_CLIENTE VARCHAR(20);
DECLARE @COMANDO NVARCHAR(MAX);

SELECT TOP (1) @CEDULA_CLIENTE = C.CEDULA
FROM DBO.CLIENTE AS C
ORDER BY C.CEDULA;

SET @COMANDO = N'
EXECUTE AS USER = ''USUARIO_ADMINISTRATIVO'';

SELECT
    USER_NAME() AS USUARIO_ACTUAL,
    IS_MEMBER(''ROL_ADMINISTRATIVO'') AS ES_ADMINISTRATIVO,
    IS_MEMBER(''ROL_OPERATIVO'') AS ES_OPERATIVO;

SELECT
    C.CEDULA,
    C.TIPO_CLIENTE,
    C.NOMBRE,
    C.RAZON_SOCIAL,
    C.SENAS_EXACTAS,
    C.FECHA_REGISTRO,
    C.FECHA_ACTUALIZACION,
    C.TELEFONO,
    C.CORREO
FROM DBO.FN_INFORMACION_CLIENTE(
    @CEDULA
) AS C;

REVERT;
';

EXEC SYS.SP_EXECUTESQL
    @COMANDO,
    N'@CEDULA VARCHAR(20)',
    @CEDULA = @CEDULA_CLIENTE;

SET @COMANDO = N'
EXECUTE AS USER = ''USUARIO_OPERATIVO'';

SELECT
    USER_NAME() AS USUARIO_ACTUAL,
    IS_MEMBER(''ROL_ADMINISTRATIVO'') AS ES_ADMINISTRATIVO,
    IS_MEMBER(''ROL_OPERATIVO'') AS ES_OPERATIVO;

SELECT
    C.CEDULA,
    C.TIPO_CLIENTE,
    C.NOMBRE,
    C.RAZON_SOCIAL,
    C.SENAS_EXACTAS,
    C.FECHA_REGISTRO,
    C.FECHA_ACTUALIZACION,
    C.TELEFONO,
    C.CORREO
FROM DBO.FN_INFORMACION_CLIENTE(
    @CEDULA
) AS C;

REVERT;
';

EXEC SYS.SP_EXECUTESQL
    @COMANDO,
    N'@CEDULA VARCHAR(20)',
    @CEDULA = @CEDULA_CLIENTE;

SET @COMANDO = N'
EXECUTE AS USER = ''USUARIO_SIN_ROL'';

SELECT
    USER_NAME() AS USUARIO_ACTUAL,
    IS_MEMBER(''ROL_ADMINISTRATIVO'') AS ES_ADMINISTRATIVO,
    IS_MEMBER(''ROL_OPERATIVO'') AS ES_OPERATIVO;

SELECT
    C.CEDULA,
    C.TIPO_CLIENTE,
    C.NOMBRE,
    C.RAZON_SOCIAL,
    C.SENAS_EXACTAS,
    C.FECHA_REGISTRO,
    C.FECHA_ACTUALIZACION,
    C.TELEFONO,
    C.CORREO
FROM DBO.FN_INFORMACION_CLIENTE(
    @CEDULA
) AS C;

REVERT;
';

EXEC SYS.SP_EXECUTESQL
    @COMANDO,
    N'@CEDULA VARCHAR(20)',
    @CEDULA = @CEDULA_CLIENTE;
GO
