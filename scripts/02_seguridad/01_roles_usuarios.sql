USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE
            NAME = 'AUDITOR'
            AND TYPE = 'R'
    )
    BEGIN
        CREATE ROLE AUDITOR
        AUTHORIZATION DBO;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE
            NAME = 'DBA'
            AND TYPE = 'R'
    )
    BEGIN
        CREATE ROLE DBA
        AUTHORIZATION DBO;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE
            NAME = 'ROL_ADMINISTRATIVO'
            AND TYPE = 'R'
    )
    BEGIN
        CREATE ROLE ROL_ADMINISTRATIVO
        AUTHORIZATION DBO;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE
            NAME = 'ROL_OPERATIVO'
            AND TYPE = 'R'
    )
    BEGIN
        CREATE ROLE ROL_OPERATIVO
        AUTHORIZATION DBO;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE NAME = 'USUARIO_AUDITOR'
    )
    BEGIN
        CREATE USER USUARIO_AUDITOR
        WITHOUT LOGIN;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE NAME = 'USUARIO_DBA'
    )
    BEGIN
        CREATE USER USUARIO_DBA
        WITHOUT LOGIN;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE NAME = 'USUARIO_ADMINISTRATIVO'
    )
    BEGIN
        CREATE USER USUARIO_ADMINISTRATIVO
        WITHOUT LOGIN;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE NAME = 'USUARIO_OPERATIVO'
    )
    BEGIN
        CREATE USER USUARIO_OPERATIVO
        WITHOUT LOGIN;
    END
GO

IF
    NOT EXISTS (
        SELECT 1
        FROM SYS.DATABASE_PRINCIPALS
        WHERE NAME = 'USUARIO_SIN_ROL'
    )
    BEGIN
        CREATE USER USUARIO_SIN_ROL
        WITHOUT LOGIN;
    END
GO

IF IS_ROLEMEMBER('AUDITOR', 'USUARIO_AUDITOR') <> 1
    BEGIN
        ALTER ROLE AUDITOR
        ADD MEMBER USUARIO_AUDITOR;
    END
GO

IF IS_ROLEMEMBER('DBA', 'USUARIO_DBA') <> 1
    BEGIN
        ALTER ROLE DBA
        ADD MEMBER USUARIO_DBA;
    END
GO

IF
    IS_ROLEMEMBER(
        'ROL_ADMINISTRATIVO',
        'USUARIO_ADMINISTRATIVO'
    ) <> 1
    BEGIN
        ALTER ROLE ROL_ADMINISTRATIVO
        ADD MEMBER USUARIO_ADMINISTRATIVO;
    END
GO

IF
    IS_ROLEMEMBER(
        'ROL_OPERATIVO',
        'USUARIO_OPERATIVO'
    ) <> 1
    BEGIN
        ALTER ROLE ROL_OPERATIVO
        ADD MEMBER USUARIO_OPERATIVO;
    END
GO
