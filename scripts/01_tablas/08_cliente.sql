USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE CLIENTE (
    CEDULA VARCHAR(20) NOT NULL,
    TIPO_CLIENTE VARCHAR(10) NOT NULL,
    NOMBRE VARCHAR(150) NULL,
    RAZON_SOCIAL VARCHAR(150) NULL,
    ID_DIRECCION INT NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    CORREO VARCHAR(100) NOT NULL,
    FECHA_REGISTRO DATETIME2(0) NOT NULL
    CONSTRAINT DF_CLIENTE_FECHA_REGISTRO
    DEFAULT SYSDATETIME(),
    FECHA_ACTUALIZACION DATETIME2(0) NOT NULL
    CONSTRAINT DF_CLIENTE_FECHA_ACTUALIZACION
    DEFAULT SYSDATETIME(),

    CONSTRAINT PK_CLIENTE
    PRIMARY KEY (CEDULA),

    CONSTRAINT FK_CLIENTE_DIRECCION
    FOREIGN KEY (ID_DIRECCION)
    REFERENCES DIRECCION (ID_DIRECCION),

    CONSTRAINT CK_CLIENTE_TIPO
    CHECK (
        (TIPO_CLIENTE = 'FISICA'
            AND NOMBRE IS NOT NULL
            AND RAZON_SOCIAL IS NULL)
        OR
        (TIPO_CLIENTE = 'JURIDICA'
            AND RAZON_SOCIAL IS NOT NULL)
    )
);
GO
