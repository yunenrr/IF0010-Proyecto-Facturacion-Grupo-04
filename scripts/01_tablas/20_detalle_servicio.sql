CREATE TABLE DETALLESERVICIO (
    ID_FACTURA BIGINT NOT NULL,
    NUMERO_LINEA INT NOT NULL,
    CODIGO_SERVICIO VARCHAR(30) NOT NULL,

    CONSTRAINT PK_DETALLESERVICIO
    PRIMARY KEY (
        ID_FACTURA,
        NUMERO_LINEA
    ),

    CONSTRAINT FK_DETALLESERVICIO_DETALLEFACTURA
    FOREIGN KEY (ID_FACTURA, NUMERO_LINEA)
    REFERENCES DETALLEFACTURA (ID_FACTURA, NUMERO_LINEA),

    CONSTRAINT FK_DETALLESERVICIO_SERVICIO
    FOREIGN KEY (CODIGO_SERVICIO)
    REFERENCES SERVICIO (CODIGO)
);
GO
