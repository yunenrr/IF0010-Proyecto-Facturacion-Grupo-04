USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE DIRECCION (
    ID_DIRECCION INT IDENTITY (1, 1) NOT NULL,
    CODIGO_PROVINCIA INT NOT NULL,
    CODIGO_CANTON INT NOT NULL,
    CODIGO_DISTRITO INT NOT NULL,
    CODIGO_BARRIO INT NOT NULL,
    SENAS_EXACTAS VARCHAR(300) NOT NULL,

    CONSTRAINT PK_DIRECCION
    PRIMARY KEY (ID_DIRECCION),

    CONSTRAINT FK_DIRECCION_BARRIO
    FOREIGN KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO,
        CODIGO_BARRIO
    )
    REFERENCES BARRIO (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO,
        CODIGO_BARRIO
    )
);
GO
