USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE PRODUCTO (
    CODIGO VARCHAR(30) NOT NULL,
    DESCRIPCION VARCHAR(200) NOT NULL,
    TIPO_PRODUCTO VARCHAR(10) NOT NULL,
    EXISTENCIA INT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL,
    ACTIVO BIT NOT NULL
    CONSTRAINT DF_PRODUCTO_ACTIVO
    DEFAULT 1,
    FECHA_CREACION DATETIME2(0) NOT NULL
    CONSTRAINT DF_PRODUCTO_FECHA_CREACION
    DEFAULT SYSDATETIME(),

    CONSTRAINT PK_PRODUCTO
    PRIMARY KEY (CODIGO),

    CONSTRAINT CK_PRODUCTO_TIPO
    CHECK (
        TIPO_PRODUCTO IN ('FISICO', 'DIGITAL')
    ),

    CONSTRAINT CK_PRODUCTO_EXISTENCIA
    CHECK (
        (TIPO_PRODUCTO = 'FISICO'
            AND EXISTENCIA IS NOT NULL
            AND EXISTENCIA >= 0)
        OR
        (TIPO_PRODUCTO = 'DIGITAL'
            AND EXISTENCIA IS NULL)
    ),

    CONSTRAINT CK_PRODUCTO_PRECIO_UNITARIO
    CHECK (PRECIO_UNITARIO > 0),

    CONSTRAINT CK_PRODUCTO_PORCENTAJE_IMPUESTO
    CHECK (
        PORCENTAJE_IMPUESTO >= 0
        AND PORCENTAJE_IMPUESTO <= 100
    )
);
GO
