USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE DISTRITO (
    CODIGO_PROVINCIA INT NOT NULL,
    CODIGO_CANTON INT NOT NULL,
    CODIGO_DISTRITO INT NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,

    CONSTRAINT PK_DISTRITO
    PRIMARY KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO
    ),

    CONSTRAINT FK_DISTRITO_CANTON
    FOREIGN KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON
    )
    REFERENCES CANTON (
        CODIGO_PROVINCIA,
        CODIGO_CANTON
    )
);
GO
