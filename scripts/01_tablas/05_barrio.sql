USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE BARRIO (
    CODIGO_PROVINCIA INT NOT NULL,
    CODIGO_CANTON INT NOT NULL,
    CODIGO_DISTRITO INT NOT NULL,
    CODIGO_BARRIO INT NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,

    CONSTRAINT PK_BARRIO
    PRIMARY KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO,
        CODIGO_BARRIO
    ),

    CONSTRAINT FK_BARRIO_DISTRITO
    FOREIGN KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO
    )
    REFERENCES DISTRITO (
        CODIGO_PROVINCIA,
        CODIGO_CANTON,
        CODIGO_DISTRITO
    )
);
GO
