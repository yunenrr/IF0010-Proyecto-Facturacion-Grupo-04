USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE DETALLEFACTURA (
    IDENTIFICADOR_COMPROBANTE VARCHAR(40) NOT NULL,
    NUMERO_LINEA INT NOT NULL,
    CODIGO_PRODUCTO VARCHAR(30) NOT NULL,
    DESCRIPCION VARCHAR(200) NOT NULL,
    CANTIDAD DECIMAL(18, 4) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL,
    SUBTOTAL DECIMAL(18, 2) NOT NULL,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL
    CONSTRAINT DF_DETALLEFACTURA_MONTO_DESCUENTO
    DEFAULT 0,
    MONTO_IMPUESTO DECIMAL(18, 2) NOT NULL,
    TOTAL_LINEA DECIMAL(18, 2) NOT NULL,

    CONSTRAINT PK_DETALLEFACTURA
    PRIMARY KEY (
        IDENTIFICADOR_COMPROBANTE,
        NUMERO_LINEA
    ),

    CONSTRAINT FK_DETALLEFACTURA_FACTURA
    FOREIGN KEY (IDENTIFICADOR_COMPROBANTE)
    REFERENCES FACTURA (IDENTIFICADOR_COMPROBANTE),

    CONSTRAINT FK_DETALLEFACTURA_PRODUCTO
    FOREIGN KEY (CODIGO_PRODUCTO)
    REFERENCES PRODUCTO (CODIGO),

    CONSTRAINT CK_DETALLEFACTURA_NUMERO_LINEA
    CHECK (NUMERO_LINEA > 0),

    CONSTRAINT CK_DETALLEFACTURA_CANTIDAD
    CHECK (CANTIDAD > 0),

    CONSTRAINT CK_DETALLEFACTURA_PRECIO_UNITARIO
    CHECK (PRECIO_UNITARIO >= 0),

    CONSTRAINT CK_DETALLEFACTURA_PORCENTAJE_IMPUESTO
    CHECK (
        PORCENTAJE_IMPUESTO >= 0
        AND PORCENTAJE_IMPUESTO <= 100
    ),

    CONSTRAINT CK_DETALLEFACTURA_SUBTOTAL
    CHECK (SUBTOTAL >= 0),

    CONSTRAINT CK_DETALLEFACTURA_MONTO_DESCUENTO
    CHECK (MONTO_DESCUENTO >= 0),

    CONSTRAINT CK_DETALLEFACTURA_MONTO_IMPUESTO
    CHECK (MONTO_IMPUESTO >= 0),

    CONSTRAINT CK_DETALLEFACTURA_TOTAL_LINEA
    CHECK (TOTAL_LINEA >= 0)
);
GO
