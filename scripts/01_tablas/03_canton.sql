USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE CANTON (
    CODIGO_PROVINCIA INT NOT NULL,
    CODIGO_CANTON INT NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,

    CONSTRAINT PK_CANTON
    PRIMARY KEY (
        CODIGO_PROVINCIA,
        CODIGO_CANTON
    ),

    CONSTRAINT FK_CANTON_PROVINCIA
    FOREIGN KEY (CODIGO_PROVINCIA)
    REFERENCES PROVINCIA (CODIGO_PROVINCIA)
);
GO
