USE FACTURACIONSOLUCIONESMAGNIFICAS;
GO

CREATE TABLE FACTURA (
    ID_FACTURA BIGINT IDENTITY (1, 1) NOT NULL,
    IDENTIFICADOR_COMPROBANTE VARCHAR(40) NOT NULL,
    CEDULA_EMPRESA VARCHAR(20) NOT NULL,
    CEDULA_CLIENTE VARCHAR(20) NOT NULL,
    CODIGO_TIPO_DOCUMENTO VARCHAR(10) NOT NULL,
    CODIGO_MONEDA CHAR(3) NOT NULL,
    ESTADO_FACTURA VARCHAR(20) NOT NULL,
    FECHA_EMISION DATETIME2(0) NOT NULL,
    SUBTOTAL DECIMAL(18, 2) NOT NULL,
    TOTAL_DESCUENTOS DECIMAL(18, 2) NOT NULL
    CONSTRAINT DF_FACTURA_TOTAL_DESCUENTOS
    DEFAULT 0,
    TOTAL_IMPUESTOS DECIMAL(18, 2) NOT NULL
    CONSTRAINT DF_FACTURA_TOTAL_IMPUESTOS
    DEFAULT 0,
    TOTAL DECIMAL(18, 2) NOT NULL,
    OBSERVACIONES VARCHAR(500) NULL,
    FECHA_CREACION DATETIME2(0) NOT NULL
    CONSTRAINT DF_FACTURA_FECHA_CREACION
    DEFAULT SYSDATETIME(),
    FECHA_MODIFICACION DATETIME2(0) NOT NULL
    CONSTRAINT DF_FACTURA_FECHA_MODIFICACION
    DEFAULT SYSDATETIME(),

    CONSTRAINT PK_FACTURA
    PRIMARY KEY (ID_FACTURA),

    CONSTRAINT UQ_FACTURA_IDENTIFICADOR_COMPROBANTE
    UNIQUE (IDENTIFICADOR_COMPROBANTE),

    CONSTRAINT FK_FACTURA_EMPRESA
    FOREIGN KEY (CEDULA_EMPRESA)
    REFERENCES EMPRESA (CEDULA),

    CONSTRAINT FK_FACTURA_CLIENTE
    FOREIGN KEY (CEDULA_CLIENTE)
    REFERENCES CLIENTE (CEDULA),

    CONSTRAINT FK_FACTURA_TIPODOCUMENTO
    FOREIGN KEY (CODIGO_TIPO_DOCUMENTO)
    REFERENCES TIPODOCUMENTO (CODIGO),

    CONSTRAINT FK_FACTURA_MONEDA
    FOREIGN KEY (CODIGO_MONEDA)
    REFERENCES MONEDA (CODIGO),

    CONSTRAINT FK_FACTURA_ESTADOFACTURA
    FOREIGN KEY (ESTADO_FACTURA)
    REFERENCES ESTADOFACTURA (ESTADO),

    CONSTRAINT CK_FACTURA_SUBTOTAL
    CHECK (SUBTOTAL > 0),

    CONSTRAINT CK_FACTURA_TOTAL_DESCUENTOS
    CHECK (TOTAL_DESCUENTOS >= 0),

    CONSTRAINT CK_FACTURA_TOTAL_IMPUESTOS
    CHECK (TOTAL_IMPUESTOS >= 0),

    CONSTRAINT CK_FACTURA_TOTAL
    CHECK (TOTAL >= 0)
);
GO
